#!/usr/bin/env python3
"""Write runtime/unicode_data.h: the Unicode data Pin's mb_* / grapheme_* / normalizer_normalize() need, taken
from Python's unicodedata (no download):
- Grapheme_Cluster_Break, Extended_Pictographic, Indic_Conjunct_Break (UAX #29 grapheme clusters)
- full lower / upper case mappings, and Cased / Case_Ignorable for the final-sigma rule (mb_strtolower)
- canonical combining classes, full canonical and compatibility decompositions, primary compositions (UAX #15)

    python3.15 tools/gen_unicode.py          (needs Python 3.15+: unicodedata.grapheme_cluster_break)

The file is committed; run this again when Python's Unicode version moves on, then tools/check_unicode.py.
"""
import os
import sys
import unicodedata as ud

if not hasattr(ud, "grapheme_cluster_break"):
    sys.exit("needs Python 3.15 or newer (unicodedata.grapheme_cluster_break)")

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
       "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Consonant", "Extend", "Linker"]
CPS = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
HANGUL = range(0xAC00, 0xD7A4)                 # decomposed and composed by arithmetic in unicode.c


def final_sigma(before, after=""):
    return (before + "Σ" + after).lower()[len(before)] == "ς"


def props(cp):
    c = chr(cp)
    v = GCB.index(ud.grapheme_cluster_break(c))
    v |= int(ud.extended_pictographic(c)) << 4
    v |= INCB.index(ud.indic_conjunct_break(c)) << 5
    # Python's str.lower() applies the final-sigma rule with Unicode's Case_Ignorable and Cased: read them back
    # from its answers, so mb_strtolower() agrees with it exactly
    if final_sigma("A" + c) and not final_sigma("1" + c):
        v |= 1 << 7                            # Case_Ignorable: skipped when looking for a cased letter
    elif final_sigma("1" + c):
        v |= 1 << 8                            # Cased (and not ignorable)
    return v


def ranges(value):
    """(first code point, value) wherever value(cp) changes; surrogates count as 0."""
    out, last = [], None
    for cp in range(0x110000):
        v = 0 if 0xD800 <= cp <= 0xDFFF else value(cp)
        if v != last:
            out.append((cp, v))
            last = v
    return out


def c_array(ctype, name, values, per_line=12):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(values[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def mapping(name, pairs):
    """A sorted map code point -> UTF-8 text: <name>_cp[], and <name>_at[] offsets into <name>_text."""
    pool, cps, at = bytearray(), [], []
    for cp, text in pairs:
        cps.append(f"0x{cp:X}")
        at.append(str(len(pool)))
        pool += text.encode()
    at.append(str(len(pool)))
    text = "".join(f"\\x{b:02X}" for b in pool)
    out = c_array("uint32_t", f"{name}_cp", cps) + c_array("uint32_t", f"{name}_at", at)
    out.append(f"static const char {name}_text[] =")
    for i in range(0, len(text), 120):
        out.append(f'    "{text[i:i + 120]}"')
    out[-1] += ";"
    return out


out = ["// Generated by tools/gen_unicode.py from Python's unicodedata (Unicode %s) — do not edit." % ud.unidata_version,
       f"#define UNI_VERSION \"{ud.unidata_version}\""]

uni = ranges(props)
out.append("// Where the properties change: bits 0-3 Grapheme_Cluster_Break (GCB_* in unicode.c), bit 4")
out.append("// Extended_Pictographic, bits 5-6 Indic_Conjunct_Break (0 None, 1 Consonant, 2 Extend, 3 Linker),")
out.append("// bit 7 Case_Ignorable, bit 8 Cased.")
out += c_array("uint32_t", "uni_start", [f"0x{cp:X}" for cp, _ in uni])
out += c_array("uint16_t", "uni_props", [str(v) for _, v in uni], 20)

ccc = ranges(lambda cp: ud.combining(chr(cp)))
out.append("// Canonical_Combining_Class, where it changes")
out += c_array("uint32_t", "ccc_start", [f"0x{cp:X}" for cp, _ in ccc])
out += c_array("uint8_t", "ccc_value", [str(v) for _, v in ccc], 20)

out.append("// Full case mappings (str.lower() / str.upper() of one code point; final sigma is in unicode.c)")
out += mapping("lower", [(cp, chr(cp).lower()) for cp in CPS if chr(cp).lower() != chr(cp) and cp != 0x3A3])
out += mapping("upper", [(cp, chr(cp).upper()) for cp in CPS if chr(cp).upper() != chr(cp)])

out.append("// Full decompositions: canonical (NFD) and compatibility (NFKD), Hangul syllables left out")
out += mapping("nfd", [(cp, ud.normalize("NFD", chr(cp))) for cp in CPS
                       if cp not in HANGUL and ud.normalize("NFD", chr(cp)) != chr(cp)])
out += mapping("nfkd", [(cp, ud.normalize("NFKD", chr(cp))) for cp in CPS
                        if cp not in HANGUL and ud.normalize("NFKD", chr(cp)) != chr(cp)])

pairs = []                                     # primary composites: a canonical pair that NFC composes back
for cp in CPS:
    d = ud.decomposition(chr(cp))
    if cp in HANGUL or not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
        pairs.append(((parts[0] << 21) | parts[1], cp))
pairs.sort()
out.append("// Primary compositions: (first << 21 | second) -> composite, sorted")
out += c_array("uint64_t", "comp_key", [f"0x{k:X}ULL" for k, _ in pairs], 6)
out += c_array("uint32_t", "comp_value", [f"0x{v:X}" for _, v in pairs])

path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "unicode_data.h")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print(f"wrote {path}: {len(uni)} property ranges, {len(ccc)} ccc ranges, {len(pairs)} compositions, "
      f"Unicode {ud.unidata_version}")
