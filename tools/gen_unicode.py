#!/usr/bin/env python3
"""Write runtime/unicode_data.h: the Unicode properties grapheme_strlen() / grapheme_substr() need
(UAX #29 extended grapheme clusters): Grapheme_Cluster_Break, Extended_Pictographic and Indic_Conjunct_Break.

    python3.15 tools/gen_unicode.py          (needs Python 3.15+: unicodedata.grapheme_cluster_break)

The table is committed; run this again when Python's Unicode version moves on, then tools/check_unicode.py.
"""
import os
import sys
import unicodedata as ud

if not hasattr(ud, "grapheme_cluster_break"):
    sys.exit("needs Python 3.15 or newer (unicodedata.grapheme_cluster_break)")

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
       "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Consonant", "Extend", "Linker"]


def props(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return 0
    c = chr(cp)
    v = GCB.index(ud.grapheme_cluster_break(c))
    v |= int(ud.extended_pictographic(c)) << 4
    v |= INCB.index(ud.indic_conjunct_break(c)) << 5
    return v


starts = []                 # (first code point, value) wherever the value changes
last = None
for cp in range(0x110000):
    v = props(cp)
    if v != last:
        starts.append((cp, v))
        last = v

out = ["// Generated by tools/gen_unicode.py from Python's unicodedata (Unicode %s) — do not edit." % ud.unidata_version,
       "// One entry where the properties change: bits 0-3 Grapheme_Cluster_Break (see GCB_* in unicode.c),",
       "// bit 4 Extended_Pictographic, bits 5-6 Indic_Conjunct_Break (0 None, 1 Consonant, 2 Extend, 3 Linker).",
       f"#define UNI_VERSION \"{ud.unidata_version}\"",
       f"static const uint32_t uni_start[{len(starts)}] = {{"]
for i in range(0, len(starts), 10):
    out.append("    " + ", ".join(f"0x{cp:X}" for cp, _ in starts[i:i + 10]) + ",")
out.append("};")
out.append(f"static const uint8_t uni_props[{len(starts)}] = {{")
for i in range(0, len(starts), 20):
    out.append("    " + ", ".join(str(v) for _, v in starts[i:i + 20]) + ",")
out.append("};")
path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "unicode_data.h")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print(f"wrote {path}: {len(starts)} ranges, Unicode {ud.unidata_version}")
